// bake-gif.mjs <input.gif> - convert a GIF into ASCII frames for the openglm-brand plugin
// Usage: node bake-gif.mjs C:\\path\\to\\clip.gif [--width 64]
import fs from 'node:fs';
import path from 'node:path';
import { GifReader } from 'omggif';

const arg = process.argv[2];
if (!arg) { console.error('usage: node bake-gif.mjs <input.gif> [--width 64]'); process.exit(1); }
const widthArg = process.argv.includes('--width') ? Number(process.argv[process.argv.indexOf('--width') + 1]) : 64;

const buf = fs.readFileSync(arg);
const reader = new GifReader(buf);
const W = reader.width, H = reader.height, N = reader.numFrames();
console.log(`gif: ${W}x${H}, ${N} frames`);

const outW = widthArg;
const outH = Math.round((H / W) * outW * 0.5); // chars are ~2x tall as wide
const RAMP = ' .,:;=+*#%@$'; // dark -> bright

const rgba = new Uint8ClampedArray(W * H * 4);
const frames = [];
const small = [];          // wide thin strip for the chat-composer background
let delaySum = 0, delayN = 0;

const SM_W = 40, SM_ROWS = 3;

for (let f = 0; f < N; f++) {
  reader.decodeAndBlitFrameRGBA(f, rgba);
  const lines = [];
  for (let y = 0; y < outH; y++) {
    let line = '';
    for (let x = 0; x < outW; x++) {
      // box-sample the source region
      const x0 = Math.floor((x * W) / outW), x1 = Math.max(x0 + 1, Math.floor(((x + 1) * W) / outW));
      const y0 = Math.floor((y * H) / outH), y1 = Math.max(y0 + 1, Math.floor(((y + 1) * H) / outH));
      let sum = 0, n = 0, alpha = 0;
      for (let yy = y0; yy < y1; yy++) for (let xx = x0; xx < x1; xx++) {
        const k = (yy * W + xx) * 4;
        const a = rgba[k + 3] / 255;
        const lum = (0.299 * rgba[k] + 0.587 * rgba[k + 1] + 0.114 * rgba[k + 2]) / 255;
        sum += lum * a; n++; alpha += a;
      }
      const v = n ? sum / Math.max(alpha / n, 0.0001) : 0;
      const bright = alpha / n < 0.25 ? 0 : v; // transparent -> dark
      const idx = Math.min(RAMP.length - 1, Math.round(bright * (RAMP.length - 1)));
      line += RAMP[idx];
    }
    lines.push(line.replace(/\s+$/, ''));
  }
  frames.push(lines.join('\n'));

  // strip: sample the middle band of the frame (where the subject usually is)
  const slines = [];
  for (let y = 0; y < SM_ROWS; y++) {
    let line = '';
    for (let x = 0; x < SM_W; x++) {
      const x0 = Math.floor((x * W) / SM_W), x1 = Math.max(x0 + 1, Math.floor(((x + 1) * W) / SM_W));
      const yc = 0.30 + (0.35 * y) / Math.max(SM_ROWS - 1, 1); // 30%..65% of height
      const y0 = Math.floor(yc * H), y1 = Math.min(H, y0 + 2);
      let sum = 0, n = 0, alpha = 0;
      for (let yy = y0; yy < y1; yy++) for (let xx = x0; xx < x1; xx++) {
        const k = (yy * W + xx) * 4;
        const a = rgba[k + 3] / 255;
        const lum = (0.299 * rgba[k] + 0.587 * rgba[k + 1] + 0.114 * rgba[k + 2]) / 255;
        sum += lum * a; n++; alpha += a;
      }
      const v = n ? sum / Math.max(alpha / n, 0.0001) : 0;
      const bright = alpha / n < 0.25 ? 0 : v;
      const idx = Math.min(RAMP.length - 1, Math.round(bright * (RAMP.length - 1)));
      line += RAMP[idx];
    }
    slines.push(line.replace(/\s+$/, ''));
  }
  small.push(slines.join('\n'));

  const d = reader.frameInfo(f).delay || 0; // in 1/100 s, 0 = as-is
  if (d > 0) { delaySum += d; delayN++; }
}

const delay = delayN ? Math.max(40, Math.round((delaySum / delayN) * 10)) : 110;

const ts = `// Baked brand frames - generated by tools/bake-gif.mjs from the source GIF.
// Do not edit by hand: the installer redeploys this file as-is.
export const DELAY_MS = ${delay}
export const FRAMES: string[] = [
${frames.map((f) => '`' + f + '`').join(',\n')},
]
export const FRAMES_SMALL: string[] = [
${small.map((f) => '`' + f + '`').join(',\n')},
]
`;

const out = 'C:/Users/Dmitry/openglm/opencode/plugins/openglm-brand/src/frames.ts';
fs.writeFileSync(out, ts);
console.log(`frames: ${frames.length} x ${outW}x${outH}, strip ${small.length} x ${small[0].split('\n')[0].length}x${small[0].split('\n').length}, delay ${delay} ms`);
console.log('written:', out);
